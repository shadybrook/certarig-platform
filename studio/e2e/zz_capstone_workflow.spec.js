import { expect, test } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';

test('configure thermal rig, block, review, deny, approve, run and export', async ({ page }) => {
  const dir = path.resolve(process.env.CERTARIG_BROWSER_EVIDENCE || '../../validation/browser');
  await fs.mkdir(dir, {recursive:true});
  await page.goto('/');
  await page.getByTestId('operator-key').fill('sim-operator-key-000001');
  await page.getByRole('button', {name:'Open Studio'}).click();
  await expect(page.locator('#health-pill')).toHaveAttribute('data-state', 'ok');
  await page.evaluate(async () => {
    const { get, post } = await import('/src/api.mjs');
    const { runs } = await get('/v1/procedure_runs');
    for (const run of runs) if (!run.ended_at) await post(`/v1/procedure_runs/${run.run_id}/abort`, {reason:'browser setup cleanup'});
  });
  await page.locator('#nav a[data-view="onboard"]').click();
  await page.getByText('Full rig configuration', {exact:true}).click();
  const config = JSON.parse(await fs.readFile(new URL('../../config/rig.thermal.capstone.json', import.meta.url), 'utf8'));
  config.channels[0].channel_id = 'reactor_temperature';
  await page.locator('#onboard-document').fill(JSON.stringify(config, null, 2));
  await page.locator('#onboard-json-propose').click();
  await expect(page.getByTestId('onboard-diff')).toContainText('next');
  await page.locator('#onboard-json-apply').click();
  await expect(page.locator('#commissioning-state')).toHaveAttribute('data-status', 'review_required');
  await page.screenshot({path:path.join(dir,'01-review-required.png'),fullPage:true});
  await page.locator('#nav a[data-view="procedures"]').click();
  await page.locator('#proc-id').selectOption('thermal_soak');
  await page.locator('#proc-start').click();
  await expect(page.locator('#toast')).toContainText('Rig is not ready');
  await page.locator('#nav a[data-view="onboard"]').click();
  await page.locator('#commission-procedure').selectOption('thermal_soak');
  await page.locator('#commission-review').click();
  await expect(page.locator('#commissioning-state')).toHaveAttribute('data-status','simulation_ready');
  await page.screenshot({path:path.join(dir,'02-simulation-ready.png'),fullPage:true});
  await page.locator('#nav a[data-view="procedures"]').click();
  await page.locator('#proc-id').selectOption('thermal_soak');
  await page.locator('#proc-start').click();
  await expect(page.locator('#view-approvals')).toBeVisible();
  await page.locator('[data-deny]').first().click();
  await expect(page.locator('[data-approval]').filter({hasText:'denied'})).toBeVisible();
  await page.locator('#nav a[data-view="procedures"]').click();
  await page.locator('#proc-id').selectOption('thermal_soak');
  await page.locator('#proc-start').click();
  await expect(page.locator('#view-approvals')).toBeVisible();
  await page.screenshot({path:path.join(dir,'03-human-approval.png'),fullPage:true});
  await page.locator('[data-grant]').first().click();
  await expect(page.locator('#active-run')).toHaveAttribute('data-status','passed',{timeout:15000});
  await page.screenshot({path:path.join(dir,'04-passed-run.png'),fullPage:true});
  const runId = await page.locator('#active-run').getAttribute('data-run');
  await page.locator('#nav a[data-view="evidence"]').click();
  const downloading = page.waitForEvent('download');
  await page.locator(`[data-export-run="${runId}"]`).click();
  await (await downloading).saveAs(path.join(dir,'browser-thermal-run.zip'));
  await page.screenshot({path:path.join(dir,'05-evidence-export.png'),fullPage:true});
  await fs.writeFile(path.join(dir,'receipt.json'),JSON.stringify({evidence_kind:'simulated',approval_actor:'automated browser test exercising human UI',provider:'fake',run_id:runId,result:'passed',channel:'reactor_temperature',assertions:['unreviewed blocked','review accepted','denial retained','explicit approval','run passed','downloaded']},null,2));
});
